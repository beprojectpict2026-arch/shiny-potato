x_test = scaler.transform(x_test)
mlp = MLPClassifier(hidden_layer_sizes=(16, 8), max_iter=100,early_stopping=True, random_state=42).fit(x_train, y_train) #imp line, write on eraser
y_pred = mlp.predict(x_test)
print(classification_report(y_test, y_pred))
cm = confusion_matrix(y_test, y_pred)
