import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_csv('/content/uber.csv')
df.dropna(inplace=True)
df.drop(["Unnamed: 0", "key"], inplace=True, axis=1)
df = df[df['fare_amount'] > 0]
df.head()

import seaborn as sns
sns.boxplot(x=df['fare_amount'])
plt.title("Before outlier remove")
plt.show()

q1=df["fare_amount"].quantile(0.25)
q3=df["fare_amount"].quantile(0.75)
iqr = q3-q1
lower = max(0, q1-1.5*iqr)
upper = q3+1.5*iqr
df=df[(df['fare_amount']>=lower) & (df["fare_amount"]<=upper)]

sns.boxplot(x=df["fare_amount"])
plt.title("After outlier remove")
plt.show()

# what is corr?
corr=df.corr(numeric_only=True)
sns.heatmap(corr, annot=True, cmap="coolwarm")
plt.show()

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_squared_error, r2_score

X = df.drop(["fare_amount", "pickup_datetime"], axis=1)
Y = df["fare_amount"]
x_train, x_test, y_train, y_test = train_test_split(X, Y, test_size=0.2, random_state=42)
lr = LinearRegression()
lr.fit(x_train, y_train)
y_pred_lr = lr.predict(x_test)

rfc = RandomForestRegressor()
rfc.fit(x_train, y_train)
y_pred_rfc = rfc.predict(x_test)

mse_lr = mean_squared_error(y_test, y_pred_lr)
r2_lr = r2_score(y_test, y_pred_lr)
mse_rfc = mean_squared_error(y_test, y_pred_rfc)
r2_rfc = r2_score(y_test, y_pred_rfc)

print("Linear Regression - MSE:", mse_lr)
print("Linear Regression - R2 Score:", r2_lr)
print("Random Forest - MSE:", mse_rfc)
print("Random Forest - R2 Score:", r2_rfc)

